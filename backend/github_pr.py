"""GitHub API operations for approved workflow remediation pull requests."""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import PurePosixPath
from uuid import uuid4

from github import Github


def _workflow_path(file_path: str) -> str:
    path = PurePosixPath(file_path)
    if path.is_absolute() or ".." in path.parts:
        raise ValueError("file_path must be a relative workflow path")
    if len(path.parts) < 3 or path.parts[0:2] != (".github", "workflows"):
        raise ValueError("file_path must be inside .github/workflows")
    if path.suffix.lower() not in {".yml", ".yaml"}:
        raise ValueError("file_path must have a .yml or .yaml extension")
    return path.as_posix()


def create_github_pr(
    repo_name: str,
    file_path: str,
    corrected_yaml: str,
    github_token: str,
    base_branch: str = "main",
) -> dict[str, str | int]:
    """Create a branch, update one existing workflow, and open a pull request."""
    if not corrected_yaml.strip():
        raise ValueError("corrected_yaml must not be empty")
    if not github_token.strip():
        raise ValueError("github_token must not be empty")
    workflow_path = _workflow_path(file_path)
    github = Github(github_token.strip())
    repository = github.get_repo(repo_name.strip())
    base = repository.get_branch(base_branch)
    branch_name = (
        "fix/cicd-security-"
        f"{datetime.now(timezone.utc).strftime('%Y%m%d%H%M%S')}-"
        f"{uuid4().hex[:8]}"
    )
    repository.create_git_ref(
        ref=f"refs/heads/{branch_name}",
        sha=base.commit.sha,
    )
    existing = repository.get_contents(workflow_path, ref=base_branch)
    if isinstance(existing, list):
        raise ValueError(f"workflow path is not a file: {workflow_path}")
    repository.update_file(
        path=workflow_path,
        message="security: remediate workflow vulnerabilities via cicd-fixer agent",
        content=corrected_yaml,
        sha=existing.sha,
        branch=branch_name,
    )
    pull_request = repository.create_pull(
        title="Security: remediate workflow vulnerabilities",
        body=(
            "Automated CI/CD security remediation generated by the "
            "cicd-fixer agent."
        ),
        head=branch_name,
        base=base_branch,
    )
    return {
        "pr_url": pull_request.html_url,
        "pr_number": pull_request.number,
        "status": "success",
        "branch": branch_name,
        "base_branch": base_branch,
        "file_path": workflow_path,
    }
